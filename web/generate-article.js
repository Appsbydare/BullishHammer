const { GoogleGenerativeAI } = require("@google/generative-ai");
const fs = require('fs');
const path = require('path');
const dotenv = require('dotenv');

// Load environment variables from .env.local
const envPath = path.resolve(__dirname, '.env.local');
if (fs.existsSync(envPath)) {
  dotenv.config({ path: envPath });
} else {
  console.error("No .env.local file found.");
  process.exit(1);
}

const GEMINI_API_KEY = process.env.GEMINI_API_KEY;
const MARKETAUX_API_TOKEN = process.env.MARKETAUX_API_TOKEN?.trim();
const AI_INGEST_SECRET = process.env.AI_INGEST_SECRET?.trim();
const POLLINATIONS_API_KEY = process.env.POLLINATIONS_API_KEY?.trim();

// ─── Image Generation Config ─────────────────────────────────────────────────
// To switch to a paid model later, simply update IMAGE_GEN_MODEL in .env.local
// e.g. gptimage, seedream-pro, kontext, gptimage-large
const IMAGE_GEN_MODEL = process.env.IMAGE_GEN_MODEL || 'flux';
const IMAGE_WIDTH = 1200;
const IMAGE_HEIGHT = 630; // OG-image standard — perfect for articles
// ─────────────────────────────────────────────────────────────────────────────

if (!GEMINI_API_KEY) {
  console.error("❌ Error: GEMINI_API_KEY is missing from .env.local");
  process.exit(1);
}

const genAI = new GoogleGenerativeAI(GEMINI_API_KEY);

async function fetchLatestNews() {
  console.log("📰 Fetching latest market news from Marketaux...");
  const res = await fetch(`https://api.marketaux.com/v1/news/all?api_token=${MARKETAUX_API_TOKEN}&language=en&limit=3`);
  if (!res.ok) throw new Error("Failed to fetch news from Marketaux");
  const data = await res.json();
  return data.data;
}

async function generateArticle(newsData) {
  console.log("🧠 Sending news data to Gemini to write an article...");
  const model = genAI.getGenerativeModel({ model: "gemini-3.5-flash", generationConfig: { responseMimeType: "application/json" } });

  const prompt = `
  You are an expert financial journalist writing for "Bullish Hammer", a premium retail FX and market analysis publication.
  
  Read the following latest market news items:
  ${JSON.stringify(newsData, null, 2)}
  
  Write a professional, engaging 300-400 word financial article synthesizing this news. 
  
  You MUST return ONLY a raw JSON object (without markdown code blocks) matching exactly this schema:
  {
    "title": "A catchy, professional headline",
    "excerpt": "A 1-2 sentence summary of the article",
    "body": "The full article text, formatted with paragraphs separated by double newlines (\\n\\n). Do NOT use markdown.",
    "categoryName": "A relevant category like 'Market Analysis', 'Economy', or 'Global News'",
    "tags": ["tag1", "tag2", "tag3"],
    "seoTitle": "SEO optimized title",
    "seoDescription": "SEO optimized description",
    "imagePrompt": "A vivid, professional image generation prompt (max 50 words) describing a photorealistic editorial banner for this article. Describe the visual scene without text or logos.",
    "aiProvenance": "Generated by Gemini 3.5 Flash on ${new Date().toISOString().split('T')[0]}"
  }
  `;

  const result = await model.generateContent(prompt);
  const responseText = result.response.text();
  
  try {
    return JSON.parse(responseText);
  } catch (e) {
    console.error("Failed to parse Gemini output as JSON:", responseText);
    throw e;
  }
}

async function generateBannerImage(imagePrompt, articleTitle) {
  console.log(`🖼️  Generating banner image via Pollinations (model: ${IMAGE_GEN_MODEL})...`);

  // Use Gemini's imagePrompt if available, otherwise fall back to article title
  const prompt = imagePrompt || `Premium financial editorial banner: ${articleTitle}, stock market, professional photography`;
  const encodedPrompt = encodeURIComponent(prompt);
  const imageUrl = `https://gen.pollinations.ai/image/${encodedPrompt}?model=${IMAGE_GEN_MODEL}&width=${IMAGE_WIDTH}&height=${IMAGE_HEIGHT}&nologo=true`;

  try {
    const headers = {};
    if (POLLINATIONS_API_KEY) {
      headers['Authorization'] = `Bearer ${POLLINATIONS_API_KEY}`;
    }

    const res = await fetch(imageUrl, { headers });

    if (!res.ok) {
      console.warn(`⚠️  Image generation returned ${res.status}. Skipping image — article will be ingested without a banner.`);
      return null;
    }

    const contentType = res.headers.get('content-type') || '';
    if (!contentType.includes('image')) {
      console.warn("⚠️  Unexpected content-type from image API. Skipping image.");
      return null;
    }

    console.log("✅ Banner image generated successfully.");
    // Return the direct URL — the ingest API will use this as an external image URL
    return imageUrl;
  } catch (err) {
    console.warn("⚠️  Image generation failed:", err.message, "— proceeding without banner.");
    return null;
  }
}

async function ingestArticle(articlePayload) {
  console.log("🚀 Submitting draft article to Bullish Hammer Ingestion API...");
  let baseUrl = process.env.NEXT_PUBLIC_SITE_URL;
  if (!baseUrl) {
    if (process.env.VERCEL_PROJECT_PRODUCTION_URL) {
      baseUrl = `https://${process.env.VERCEL_PROJECT_PRODUCTION_URL}`;
    } else if (process.env.VERCEL_URL) {
      baseUrl = `https://${process.env.VERCEL_URL}`;
    } else {
      baseUrl = 'http://localhost:3000';
    }
  }
  const res = await fetch(`${baseUrl}/api/ingest`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'Authorization': `Bearer ${AI_INGEST_SECRET}`
    },
    body: JSON.stringify(articlePayload)
  });

  const result = await res.json();
  if (res.ok) {
    console.log("✅ Success! Draft created in Sanity with ID:", result.documentId);
    if (articlePayload.bannerImageUrl) {
      console.log("🖼️  Banner Image URL:", articlePayload.bannerImageUrl);
    }
  } else {
    console.error("❌ Failed to ingest:", result);
  }
}

async function run() {
  try {
    const news = await fetchLatestNews();
    const articleData = await generateArticle(news);
    
    console.log("\n📝 Gemini Drafted:", articleData.title, "\n");

    // Generate banner image using Gemini's image prompt
    const bannerImageUrl = await generateBannerImage(articleData.imagePrompt, articleData.title);

    // Build final payload (strip imagePrompt, add bannerImageUrl)
    const { imagePrompt, ...cleanPayload } = articleData;
    const articlePayload = {
      ...cleanPayload,
      ...(bannerImageUrl && { bannerImageUrl }),
    };

    await ingestArticle(articlePayload);
  } catch (err) {
    console.error("Error during generation pipeline:", err);
  }
}

run();
