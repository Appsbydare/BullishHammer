"use server";

import { GoogleGenAI } from "@google/genai";
import { revalidatePath } from "next/cache";
import { cookies } from "next/headers";

export async function fetchNewsAction(category: string) {
  const cookieStore = await cookies();
  if (cookieStore.get("admin_session")?.value !== "true") return { error: "Unauthorized" };
  try {
    const MARKETAUX_API_TOKEN = process.env.MARKETAUX_API_TOKEN?.trim();
    if (!MARKETAUX_API_TOKEN) {
      return { error: "MARKETAUX_API_TOKEN is missing." };
    }

    // Use the category to refine the search. If it's empty or 'All Latest News', get general news.
    const query = (!category || category === "All Latest News") ? "" : `&search=${encodeURIComponent(category)}`;
    
    console.log(`fetching news with query: ${query}`);
    const res = await fetch(`https://api.marketaux.com/v1/news/all?api_token=${MARKETAUX_API_TOKEN}&language=en&limit=5${query}`);
    
    if (!res.ok) {
      throw new Error(`Marketaux API error: ${res.statusText}`);
    }
    
    const data = await res.json();
    return { success: true, data: data.data };
  } catch (error: any) {
    console.error("fetchNewsAction error:", error);
    return { error: error.message || "Failed to fetch news." };
  }
}

export async function generateArticleAction(newsData: any[], customInstructions: string) {
  const cookieStore = await cookies();
  if (cookieStore.get("admin_session")?.value !== "true") return { error: "Unauthorized" };

  try {
    const GEMINI_API_KEY = process.env.GEMINI_API_KEY;
    const AI_INGEST_SECRET = process.env.AI_INGEST_SECRET?.trim();
    
    if (!GEMINI_API_KEY) return { error: "GEMINI_API_KEY is missing." };
    if (!AI_INGEST_SECRET) return { error: "AI_INGEST_SECRET is missing." };

    const ai = new GoogleGenAI({ apiKey: GEMINI_API_KEY });
    const geminiModel = process.env.GEMINI_MODEL?.trim() || "gemini-2.0-flash";

    const instructionsAddition = customInstructions ? `\n\nCRITICAL CUSTOM INSTRUCTIONS from the Editor:\n"${customInstructions}"\nYou MUST strictly follow these instructions in your writing.` : "";

    const prompt = `
    You are an expert financial journalist writing for "Bullish Hammer", a premium retail FX and market analysis publication.
    
    Read the following curated market news items:
    ${JSON.stringify(newsData, null, 2)}
    ${instructionsAddition}
    
    Write a professional, engaging 300-400 word financial article synthesizing this news. 
    
    You MUST return ONLY a raw JSON object (without markdown code blocks) matching exactly this schema:
    {
      "title": "A catchy, professional headline",
      "excerpt": "A 1-2 sentence summary of the article",
      "body": "The full article text, formatted with paragraphs separated by double newlines (\\n\\n). Do NOT use markdown.",
      "categoryName": "A relevant category like 'Market Analysis', 'Economy', or 'Global News'",
      "tags": ["tag1", "tag2", "tag3"],
      "seoTitle": "SEO optimized title",
      "seoDescription": "SEO optimized description",
      "imagePrompt": "A detailed DALL-E/Flux prompt to generate a high-quality professional financial news cover image based on the article content.",
      "aiProvenance": "Generated by ${geminiModel} on ${new Date().toISOString().split('T')[0]}"
    }
    `;

    const response = await ai.models.generateContent({
      model: geminiModel,
      contents: prompt,
      config: { responseMimeType: "application/json" },
    });
    const responseText = response.text ?? "";
    
    let articlePayload;
    try {
      articlePayload = JSON.parse(responseText);
    } catch (e) {
      throw new Error("Failed to parse AI output. The AI did not return valid JSON.");
    }

    // Generate cover image via Pollinations.ai (Flux model) — non-fatal
    try {
      const imagePromptText = articlePayload.imagePrompt ||
        `Cinematic premium editorial financial news cover image for article: "${articlePayload.title}". Professional photography, dark dramatic lighting, financial markets, 4K quality.`;
      const pollinationsUrl = `https://image.pollinations.ai/prompt/${encodeURIComponent(imagePromptText)}?width=1280&height=720&model=flux&nologo=true&seed=${Date.now()}`;
      console.log("Generating cover image from Pollinations Flux...");
      const imgRes = await fetch(pollinationsUrl, { signal: AbortSignal.timeout(45000) });
      if (imgRes.ok) {
        const arrayBuffer = await imgRes.arrayBuffer();
        articlePayload.coverImageBase64 = Buffer.from(arrayBuffer).toString('base64');
        articlePayload.coverImageMimeType = imgRes.headers.get('content-type') || 'image/jpeg';
        console.log("Cover image generated successfully.");
      } else {
        console.warn(`Pollinations returned ${imgRes.status}, skipping cover image.`);
      }
    } catch (imgErr: any) {
      console.warn("Cover image generation failed (non-fatal):", imgErr.message);
    }

    // Ingest the article
    let baseUrl = process.env.NEXT_PUBLIC_SITE_URL;
    if (!baseUrl) {
      if (process.env.VERCEL_PROJECT_PRODUCTION_URL) {
        baseUrl = `https://${process.env.VERCEL_PROJECT_PRODUCTION_URL}`;
      } else if (process.env.VERCEL_URL) {
        baseUrl = `https://${process.env.VERCEL_URL}`;
      } else {
        baseUrl = 'http://localhost:3000';
      }
    }
    const res = await fetch(`${baseUrl}/api/ingest`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Authorization': `Bearer ${AI_INGEST_SECRET}`
      },
      body: JSON.stringify(articlePayload)
    });

    const ingestResult = await res.json();
    if (!res.ok) {
      throw new Error(`Ingestion failed: ${JSON.stringify(ingestResult)}`);
    }

    revalidatePath("/admin");
    return { success: true };
  } catch (error: any) {
    console.error("generateArticleAction error:", error);
    return { error: error.message || "Failed to generate article." };
  }
}
