export async function generateArticlePreviewAction(newsData: any[], customInstructions: string) {
  const cookieStore = await cookies();
  if (cookieStore.get("admin_session")?.value !== "true") return { error: "Unauthorized" };

  try {
    const cfg = getAIConfig();
    const provider = cfg.provider;
    const modelName = provider === "openrouter" ? cfg.openrouterModel : cfg.geminiModel;

    const instructionsAddition = customInstructions
      ? `\n\nCRITICAL CUSTOM INSTRUCTIONS from the Editor:\n"${customInstructions}"\nYou MUST strictly follow these instructions in your writing.`
      : "";

    const prompt = `
    You are an expert financial journalist writing for "Bullish Hammer", a premium retail FX and market analysis publication.
    
    Read the following curated market news items:
    ${JSON.stringify(newsData, null, 2)}
    ${instructionsAddition}
    
    Write a professional, engaging 300-400 word financial article synthesizing this news. 
    
    You MUST return ONLY a raw JSON object (without markdown code blocks) matching exactly this schema:
    {
      "title": "A catchy, professional headline",
      "excerpt": "A 1-2 sentence summary of the article",
      "body": "The full article text, formatted with paragraphs separated by double newlines (\\n\\n). Do NOT use markdown.",
      "categoryName": "A relevant category like 'Market Analysis', 'Economy', or 'Global News'",
      "tags": ["tag1", "tag2", "tag3"],
      "seoTitle": "SEO optimized title",
      "seoDescription": "SEO optimized description",
      "imagePrompt": "A detailed DALL-E/Flux prompt to generate a high-quality professional financial news cover image based on the article content.",
      "aiProvenance": "Generated by ${modelName} via ${provider} on ${new Date().toISOString().split("T")[0]}"
    }
    `;

    console.log(`[AI] Generating with provider=${provider} model=${modelName}`);

    let responseText: string;
    if (provider === "openrouter") {
      if (!cfg.openrouterKey) return { error: "OpenRouter API key is missing. Configure it in Settings." };
      responseText = await generateWithOpenRouter(prompt, modelName, cfg.openrouterKey);
    } else {
      if (!cfg.geminiKey) return { error: "Gemini API key is missing. Configure it in Settings." };
      responseText = await generateWithGemini(prompt, modelName, cfg.geminiKey);
    }

    let articlePayload: any;
    try {
      const cleaned = responseText.replace(/^```(?:json)?\s*/i, "").replace(/\s*```$/i, "").trim();
      articlePayload = JSON.parse(cleaned);
    } catch (e) {
      throw new Error("Failed to parse AI output. The AI did not return valid JSON.");
    }

    try {
      const imagePromptText = articlePayload.imagePrompt ||
        `Cinematic premium editorial financial news cover image for article: "${articlePayload.title}". Professional photography, dark dramatic lighting, financial markets, 4K quality.`;
      const seed = Math.floor(Math.random() * 2000000000);
      const pollinationsUrl = `https://image.pollinations.ai/prompt/${encodeURIComponent(imagePromptText)}?width=1280&height=720&model=sana&nologo=true&enhance=true&seed=${seed}`;
      console.log("Generating cover image from Pollinations (sana)...");
      const imgRes = await fetch(pollinationsUrl, { signal: AbortSignal.timeout(45000) });
      if (imgRes.ok) {
        const arrayBuffer = await imgRes.arrayBuffer();
        articlePayload.coverImageBase64 = Buffer.from(arrayBuffer).toString("base64");
        articlePayload.coverImageMimeType = imgRes.headers.get("content-type") || "image/jpeg";
        console.log("Cover image generated successfully.");
      } else {
        console.warn(`Pollinations returned ${imgRes.status}, skipping cover image.`);
      }
    } catch (imgErr: any) {
      console.warn("Cover image generation failed (non-fatal):", imgErr.message);
    }

    return { success: true, payload: articlePayload };
  } catch (error: any) {
    console.error("generateArticlePreviewAction error:", error);
    return { error: error.message || "Failed to generate article preview." };
  }
}

export async function saveArticleDraftAction(articlePayload: any) {
  const cookieStore = await cookies();
  if (cookieStore.get("admin_session")?.value !== "true") return { error: "Unauthorized" };

  try {
    // Call the ingestion logic in-process. Previously this made an HTTP request
    // back to our own /api/ingest route, which required knowing the deployment
    // URL and breaks under Vercel Deployment Protection.
    await ingestArticle(articlePayload);

    revalidatePath("/admin");
    revalidatePath("/");
    return { success: true };
  } catch (error: any) {
    console.error("saveArticleDraftAction error:", error);
    return { error: error.message || "Failed to save article draft." };
  }
}

export async function generateImagePromptAction(title: string, excerpt: string) {
  const cookieStore = await cookies();
  if (cookieStore.get("admin_session")?.value !== "true") return { error: "Unauthorized" };

  try {
    const cfg = getAIConfig();
    const provider = cfg.provider;
    const modelName = provider === "openrouter" ? cfg.openrouterModel : cfg.geminiModel;

    const prompt = `You are an expert AI image prompt engineer. 
    Write a highly detailed, cinematic, and professional image generation prompt for a financial news cover image. 
    The image is for an article titled "${title}".
    Excerpt: "${excerpt}"
    
    The prompt should specify dark dramatic lighting, financial markets, 4K quality, and a premium editorial style. 
    Return ONLY the prompt string, no markdown, no quotes, no extra text.`;

    let responseText: string;
    if (provider === "openrouter") {
      if (!cfg.openrouterKey) return { error: "OpenRouter API key missing" };
      // Override response format to text since we just want a string
      const res = await fetch("https://openrouter.ai/api/v1/chat/completions", {
        method: "POST",
        headers: {
          Authorization: `Bearer ${cfg.openrouterKey}`,
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          model: modelName,
          messages: [{ role: "user", content: prompt }]
        }),
      });
      if (!res.ok) throw new Error("OpenRouter prompt generation failed");
      const data = await res.json();
      responseText = data.choices?.[0]?.message?.content ?? "";
    } else {
      if (!cfg.geminiKey) return { error: "Gemini API key missing" };
      const ai = new GoogleGenAI({ apiKey: cfg.geminiKey });
      const response = await ai.models.generateContent({
        model: modelName,
        contents: prompt
      });
      responseText = response.text ?? "";
    }

    return { success: true, prompt: responseText.trim() };
  } catch (error: any) {
    console.error("generateImagePromptAction error:", error);
    return { error: error.message || "Failed to generate image prompt." };
  }
}

export async function applyImageToArticleAction(articleId: string, base64Data: string, mimeType: string = "image/jpeg") {
  const cookieStore = await cookies();
  if (cookieStore.get("admin_session")?.value !== "true") return { error: "Unauthorized" };

  try {
    const { writeClient } = await import("@/sanity/write-client");
    
    // The base64Data comes as a data URL (e.g., data:image/jpeg;base64,...), we need the raw base64 part
    const base64String = base64Data.split(',')[1] || base64Data;
    const buffer = Buffer.from(base64String, 'base64');
    
    const ext = mimeType.includes('png') ? 'png' : 'jpg';
    
    const asset = await writeClient.assets.upload('image', buffer, {
      filename: `cover-apply-${Date.now()}.${ext}`,
      contentType: mimeType,
    });
    
    await writeClient.patch(articleId).set({ 
      coverImage: { _type: 'image', asset: { _type: 'reference', _ref: asset._id } } 
    }).commit();
    
    revalidatePath("/admin");
    revalidatePath("/");
    
    return { success: true };
  } catch (error: any) {
    console.error("applyImageToArticleAction error:", error);
    return { error: error.message || "Failed to apply image." };
  }
}
